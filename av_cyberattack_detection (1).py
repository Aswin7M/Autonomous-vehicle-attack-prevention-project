def generate_hardened_can_dataset(n_samples=100_000, random_state=42):

    rng = np.random.default_rng(random_state)
    N   = n_samples

    counts = {
        'Normal':        int(N * 0.70),
        'Flood':         int(N * 0.10),
        'Fuzzy':         int(N * 0.09),
        'Spoofing_Gear': int(N * 0.06),
        'Spoofing_RPM':  int(N * 0.05),
    }
    counts['Normal'] += N - sum(counts.values())

    label_map   = {'Normal':0,'Flood':1,'Fuzzy':2,'Spoofing_Gear':3,'Spoofing_RPM':4}
    NORMAL_IDS  = [0x043F, 0x0130, 0x0260, 0x0153, 0x0545, 0x0316, 0x018F, 0x02A0]

    # ── [H4/H5] Overlapping RPM and gear operating ranges ────────────────────
    # Normal ECU RPM can legitimately reach 4500–6000 during acceleration.
    # Attack RPM now starts at 4500 → genuine overlap.
    NORMAL_RPM_MAX   = 6500    # Normal driving goes up to this occasionally
    ATTACK_RPM_MIN   = 4500    # Overlap zone: 4500–6500
    ATTACK_RPM_MAX   = 9000

    # Normal gears: 1–5 in regular driving.
    # Attack gears: 3–7 → gears 3–5 overlap completely.
    ATTACK_GEAR_MIN  = 3
    ATTACK_GEAR_MAX  = 7

    records       = []
    t             = 0.0
    total_so_far  = 0

    for cls, cnt in counts.items():
        lbl = label_map[cls]

        # [H1] Significantly larger border zone fractions
        border_frac = {
            'Normal':        0.05,   # 5% of Normal look like mild attacks
            'Flood':         0.30,   # 30% of Flood look Normal (hardest class)
            'Fuzzy':         0.25,
            'Spoofing_Gear': 0.25,
            'Spoofing_RPM':  0.25,
        }[cls]

        for i in range(cnt):
            is_border  = (rng.random() < border_frac)
            # Extra "deep border" — 10% of border samples are in the deepest overlap zone
            is_deep_border = is_border and (rng.random() < 0.10)

            # ── [H6] TIMESTAMP with widened jitter (±35%) ────────────────────
            if cls == 'Normal':
                base_iat = rng.uniform(0.001, 0.015)
            elif cls == 'Flood':
                # [H6] Border Flood now fully overlaps Normal tail
                if is_deep_border:
                    base_iat = rng.uniform(0.003, 0.010)   # deep in Normal range
                elif is_border:
                    base_iat = rng.uniform(0.0010, 0.0040)  # Normal lower tail
                else:
                    base_iat = rng.uniform(0.0001, 0.0005)
            elif cls == 'Fuzzy':
                if is_border:
                    base_iat = rng.uniform(0.0008, 0.0030)  # overlaps Normal
                else:
                    base_iat = rng.uniform(0.0002, 0.0008)
            elif cls == 'Spoofing_Gear':
                if is_border:
                    base_iat = rng.uniform(0.0015, 0.0060)  # Normal-like
                else:
                    base_iat = rng.uniform(0.0007, 0.0015)
            else:  # Spoofing_RPM
                if is_border:
                    base_iat = rng.uniform(0.0015, 0.0060)
                else:
                    base_iat = rng.uniform(0.0007, 0.0015)

            # [H6] Jitter raised from ±15% → ±35%
            jitter = rng.normal(0, base_iat * 0.35)
            t     += max(0.00005, base_iat + jitter)

            # ── ARBITRATION ID ────────────────────────────────────────────────
            if cls == 'Normal':
                arb = int(rng.choice(NORMAL_IDS))
            elif cls == 'Flood':
                # [H3] 30% of Flood now uses valid NORMAL_IDS
                if is_border or (rng.random() < 0.30):
                    arb = int(rng.choice(NORMAL_IDS))
                else:
                    arb = 0x0000
            elif cls == 'Fuzzy':
                arb = int(rng.integers(0, 2048))
            elif cls == 'Spoofing_Gear':
                arb = int(rng.choice(NORMAL_IDS)) if is_border else 0x0260
            else:  # Spoofing_RPM
                arb = int(rng.choice(NORMAL_IDS)) if is_border else 0x0316

            # ── DLC ───────────────────────────────────────────────────────────
            if cls == 'Normal':
                dlc = int(rng.choice([4,6,7,8], p=[0.10,0.20,0.30,0.40]))
            elif cls == 'Flood' and is_border:
                # Border Flood: variable DLC like Normal
                dlc = int(rng.choice([6,7,8], p=[0.25,0.35,0.40]))
            else:
                dlc = 8

            # ── [H11] PAYLOAD with AMPLIFIED sensor drift ────────────────────
            # Dual-frequency drift: thermal (slow) + vibration (fast)
            progress    = total_so_far / N
            drift_slow  = int(15 * np.sin(2 * np.pi * progress * 2))
            drift_fast  = int(10 * np.sin(2 * np.pi * progress * 7 + 1.2))
            drift_val   = drift_slow + drift_fast   # ±25 combined

