def squeeze_excitation(x, reduction=4):
    n_ch = x.shape[-1]
    z = layers.GlobalAveragePooling1D()(x)
    z = layers.Dense(max(1, n_ch // reduction), activation='relu')(z)
    z = layers.Dense(n_ch, activation='sigmoid')(z)
    z = layers.Reshape((1, n_ch))(z)
    return layers.Multiply()([x, z])


def residual_se_block(x, filters, kernel_size=3):
    shortcut = x
    out = layers.Conv1D(filters, kernel_size, padding='same', use_bias=False)(x)
    out = layers.BatchNormalization()(out)
    out = layers.Activation('relu')(out)
    out = layers.Conv1D(filters, kernel_size, padding='same', use_bias=False)(out)
    out = layers.BatchNormalization()(out)
    out = squeeze_excitation(out, reduction=4)
    if shortcut.shape[-1] != filters:
        shortcut = layers.Conv1D(filters, 1, padding='same', use_bias=False)(shortcut)
        shortcut = layers.BatchNormalization()(shortcut)
    out = layers.Add()([out, shortcut])
    out = layers.Activation('relu')(out)
    return out


def build_ra_cbilstm(seq_len, n_features, n_classes, dropout=0.45):
    """
    Residual Attention CNN-BiLSTM (RA-CBiLSTM) — Constrained for realistic accuracy.

    Constraints vs original:
      • Dropout 0.35 → 0.45 (stronger regularization on noisy data)
      • L2 coefficient 2e-4 → 5e-4
      • Dense(256) → Dense(128),  Dense(128) → Dense(64)
      • BiLSTM(128) → BiLSTM(96), BiLSTM(64) → BiLSTM(48)
      • recurrent_dropout maintained at 0.15 (prevents LSTM memorisation)

    These constraints, combined with the harder dataset, ensure that
    the model cannot simply memorise class-specific patterns and must
    generalise across genuinely ambiguous CAN frame sequences.
    """
    inp = keras.Input(shape=(seq_len, n_features), name='CAN_input')

    x = layers.Conv1D(64, 1, padding='same', use_bias=False, name='init_proj')(inp)
    x = layers.BatchNormalization()(x)
    x = layers.Activation('relu')(x)

    x = residual_se_block(x, filters=64,  kernel_size=3)
    x = layers.Dropout(dropout)(x)
    x = residual_se_block(x, filters=128, kernel_size=3)
    x = layers.Dropout(dropout)(x)

    x = layers.Bidirectional(
            layers.LSTM(96, return_sequences=True,         # reduced from 128
                        dropout=0.25, recurrent_dropout=0.15),
            name='BiLSTM_1')(x)
    x = layers.Bidirectional(
            layers.LSTM(48, return_sequences=False, dropout=0.25),   # reduced from 64
            name='BiLSTM_2')(x)

    x = layers.Dense(128, activation='relu',               # reduced from 256
                     kernel_regularizer=regularizers.l2(5e-4))(x)
    x = layers.BatchNormalization()(x)
    x = layers.Dropout(dropout)(x)
    x = layers.Dense(64, activation='relu',                # reduced from 128
                     kernel_regularizer=regularizers.l2(5e-4))(x)
    x = layers.Dropout(dropout / 2)(x)
    out = layers.Dense(n_classes, activation='softmax', name='attack_class')(x)

    return models.Model(inp, out, name='RA_CBiLSTM')


